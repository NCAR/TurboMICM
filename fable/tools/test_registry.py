#!/usr/bin/env python3
"""Write tests/registry.h (the table of test groups found in tests/test_*.c) and
tests/case_list.inc (the reference case ids as C string literals), so the
test binary prints exactly the reference list.

    test_registry.py CASE_LIST TESTS_DIR OUT_DIR
"""
import re
import sys
from pathlib import Path

case_list, tests_dir, out_dir = map(Path, sys.argv[1:4])
groups = []
for src in sorted(tests_dir.glob("test_*.c")):
    for name in re.findall(r"const tmc_test_case \*(tmc_tests_\w+)\(int \*n\)\s*\{", src.read_text()):
        groups.append(name)
registry = ["/* Generated by tools/test_registry.py. Do not edit. */", "#ifndef TMC_TEST_REGISTRY_H", "#define TMC_TEST_REGISTRY_H", '#include "harness.h"']
registry += [f"const tmc_test_case *{g}(int *n);" for g in groups]
registry += ["static const tmc_test_case *const *tmc_test_groups(int *n_groups)", "{", "  static const tmc_test_case *groups[%d];" % (len(groups) + 1), "  int n;", "  int k = 0;"]
registry += [f"  groups[k++] = {g}(&n);" for g in groups]
registry += ["  groups[k] = NULL;", "  *n_groups = k;", "  return groups;", "}", "#endif", ""]
(out_dir / "registry.h").write_text("\n".join(registry))
ids = []
for line in case_list.read_text().splitlines():
    line = line.strip()
    if not line or line.startswith("#"):
        continue
    ids.append(line.split()[0])
(out_dir / "case_list.inc").write_text("".join(f'  "{i}",\n' for i in ids))
print(f"{len(groups)} test groups, {len(ids)} cases")
